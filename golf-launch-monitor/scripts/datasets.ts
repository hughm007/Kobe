/**
 * Shared, deterministic construction of the synthetic replay dataset and its golden summary.
 * Used by scripts/generate-datasets.ts (writes files) and tests/golden (verifies them).
 */
import { DEFAULT_INDOOR_ENVIRONMENT, getBallProfile, PHYSICS_MODEL_VERSION } from "@glm/ballistics";
import { GROUND_MODEL_VERSION } from "@glm/ground-physics";
import { ESTIMATOR_VERSION } from "@glm/launch-state";
import {
  createReplayHeader,
  defaultSyntheticSensorConfiguration,
  type ParsedReplay,
  ReplaySensorAdapter,
  serializeReplay,
  SyntheticSensorAdapter,
} from "@glm/sensor-adapters";
import type { RawSensorObservation, ShotRecord } from "@glm/shared-types";
import { COORDINATE_SYSTEM_VERSION, SCHEMA_VERSION } from "@glm/shared-types";
import {
  createRangePipelineConfig,
  createTruthPropagator,
  deterministicIds,
  fixtureShotSpec,
  ShotPipeline,
  SYNTHETIC_FIXTURES,
} from "@glm/shot-pipeline";

export const DATASET_NAME = "range-fixtures";
export const DATASET_CREATED_UTC = "2026-01-01T00:00:00.000Z";
export const GOLDEN_MONTE_CARLO_SAMPLES = 50;

/** Builds the synthetic replay text for every fixture (seed 1000 + index). */
export async function buildSyntheticReplayText(): Promise<string> {
  const env = DEFAULT_INDOOR_ENVIRONMENT;
  const ball = getBallProfile("premium-urethane-baseline");
  const configuration = defaultSyntheticSensorConfiguration("synthetic-1");
  const adapter = new SyntheticSensorAdapter({
    sensorId: "synthetic-1",
    shots: SYNTHETIC_FIXTURES.map((f, i) => fixtureShotSpec(f, { seed: 1000 + i })),
    propagate: createTruthPropagator(env, ball),
    configuration,
  });
  const observations: RawSensorObservation[] = [];
  adapter.subscribeToObservations((o) => observations.push(o));
  await adapter.connect();
  await adapter.startCapture();
  await adapter.stopCapture();
  const header = createReplayHeader({
    dataOrigin: "synthetic",
    description:
      "Synthetic range session: one shot per fixture in @glm/shot-pipeline SYNTHETIC_FIXTURES. " +
      "Generated by scripts/generate-datasets.ts. Not measured data.",
    sensorConfiguration: configuration,
    calibration: null,
    syntheticTruth: adapter.getSyntheticTruth(),
    createdUtc: DATASET_CREATED_UTC,
  });
  return serializeReplay({ header, observations });
}

/** Runs a parsed replay through the standard range pipeline with deterministic ids. */
export async function runReplay(replay: ParsedReplay, monteCarloSamples = GOLDEN_MONTE_CARLO_SAMPLES): Promise<ShotRecord[]> {
  const adapter = new ReplaySensorAdapter(replay);
  const config = createRangePipelineConfig({
    sessionId: `replay-${DATASET_NAME}`,
    environment: DEFAULT_INDOOR_ENVIRONMENT,
    sensorConfiguration: adapter.getConfiguration(),
    dataOrigin: adapter.capabilities.dataOrigin,
    ...deterministicIds("replay-shot"),
    simulationSettings: { monteCarloSamples },
    // A recording carries the calibration it was captured with; ignoring it would mark every
    // live replay invalid (or, worse, judge it against the wrong calibration).
    overrides: { calibration: replay.header.calibration },
  });
  const pipeline = new ShotPipeline(adapter, config);
  const records: ShotRecord[] = [];
  pipeline.onShot((r) => records.push(r));
  pipeline.attach();
  await adapter.connect();
  await adapter.startCapture();
  pipeline.flush();
  await adapter.stopCapture();
  return records;
}

export type GoldenShot = {
  readonly label: string;
  readonly validity: string;
  readonly spinMode: string;
  readonly overallConfidence: number;
  readonly ballSpeedMps: number | null;
  readonly verticalLaunchAngleDeg: number | null;
  readonly horizontalLaunchAngleDeg: number | null;
  readonly totalSpinRpm: number | null;
  readonly spinAxisTiltDeg: number | null;
  readonly carryM: number | null;
  readonly carryP05M: number | null;
  readonly carryP95M: number | null;
  readonly carryLateralM: number | null;
  readonly totalM: number | null;
  readonly totalLateralM: number | null;
  readonly apexHeightM: number | null;
  readonly descentAngleRad: number | null;
  readonly flightTimeS: number | null;
  readonly curveM: number | null;
};

export type GoldenFile = {
  readonly dataset: string;
  readonly schemaVersion: string;
  readonly coordinateSystemVersion: string;
  readonly physicsModelVersion: string;
  readonly groundModelVersion: string;
  readonly estimatorVersion: string;
  readonly monteCarloSamples: number;
  readonly shots: readonly GoldenShot[];
};

export function summarize(records: readonly ShotRecord[], labels: readonly string[]): GoldenFile {
  return {
    dataset: DATASET_NAME,
    schemaVersion: SCHEMA_VERSION,
    coordinateSystemVersion: COORDINATE_SYSTEM_VERSION,
    physicsModelVersion: PHYSICS_MODEL_VERSION,
    groundModelVersion: GROUND_MODEL_VERSION,
    estimatorVersion: ESTIMATOR_VERSION,
    monteCarloSamples: GOLDEN_MONTE_CARLO_SAMPLES,
    shots: records.map((r, i) => {
      const m = r.result?.metrics;
      return {
        label: labels[i] ?? `shot-${i}`,
        validity: r.launch.validity,
        spinMode: r.launch.spinMode,
        overallConfidence: r.launch.overallConfidence,
        ballSpeedMps: r.launch.ballSpeedMps.value,
        verticalLaunchAngleDeg: r.launch.verticalLaunchAngleDeg.value,
        horizontalLaunchAngleDeg: r.launch.horizontalLaunchAngleDeg.value,
        totalSpinRpm: r.launch.totalSpinRpm.value,
        spinAxisTiltDeg: r.launch.spinAxisTiltDeg.value,
        carryM: m?.carryM.value ?? null,
        carryP05M: m?.carryM.interval?.p05 ?? null,
        carryP95M: m?.carryM.interval?.p95 ?? null,
        carryLateralM: m?.carryLateralM.value ?? null,
        totalM: m?.totalM.value ?? null,
        totalLateralM: m?.totalLateralM.value ?? null,
        apexHeightM: m?.apexHeightM.value ?? null,
        descentAngleRad: m?.descentAngleRad.value ?? null,
        flightTimeS: m?.flightTimeS.value ?? null,
        curveM: m?.curveM.value ?? null,
      };
    }),
  };
}
